import { expect, test, type Page } from '@playwright/test';

test.setTimeout(60_000);
async function readLocal(page: Page) {
  return page.evaluate(async () => {
    const path = '/src/persistence/db.ts';
    const { database } = await import(/* @vite-ignore */ path);
    return { guided: await database.guidedStates.get('guided'), sessions: await database.sessions.toArray(), sets: await database.sets.toArray() };
  });
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
}

