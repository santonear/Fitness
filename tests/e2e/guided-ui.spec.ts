  await dialog.getByRole('button', { name: '确认重新开始' }).click();
  await expect(page.getByRole('heading', { name: '你的年龄是多少？' })).toBeVisible();
  const after = await readLocal(page);
  expect(after.guided.onboarding?.answers ?? {}).toEqual({});
  expect(after.sessions).toEqual(before.sessions); expect(after.sets).toEqual(before.sets);
  await page.locator('.language-control select').selectOption('en');
  await expect(page.getByRole('heading', { name: 'how old are you?' })).toBeVisible();
  await noOverflow(page);
  await page.screenshot({ path: testInfo.outputPath('welcome-en-320.png'), fullPage: true, animations: 'disabled' });
