/** Commit generated.ts alongside Markdown sources. Wrangler bundles TS directly. */
import { readFile, writeFile } from 'node:fs/promises';
const paths=['persona','safety','text','intent','repair','tasks/plan','tasks/today','tasks/modify','tasks/review'];
const base=new URL('./v3.0.0/',import.meta.url);
const sections=Object.fromEntries(await Promise.all(paths.map(async path=>[path,await readFile(new URL(`${path}.md`,base),'utf8')])));
await writeFile(new URL('./generated.ts',import.meta.url),`// Generated by node src/backend/assistant/prompts/build.mjs; edit the Markdown sources.\nexport const v3PromptSections = ${JSON.stringify(sections,null,2)} as const;\n`);
