export type UserLabelGroup = keyof typeof userLabels;
/** Unknown server values receive a neutral label, never a raw enum or arbitrary text. */
export function userLabel(group: UserLabelGroup, value: string, language = 'zh'): string {
  const labels: Labels = userLabels[group];
  return (
    labels[value]?.[language.startsWith('en') ? 1 : 0] ??
    (language.startsWith('en') ? 'Other / not recorded' : '其他或尚未记录')
  );
}
